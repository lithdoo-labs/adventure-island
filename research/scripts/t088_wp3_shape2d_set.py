def load(path, sha):
    data = open(path, "rb").read()
    if hashlib.sha256(data).hexdigest() != sha:
        raise SystemExit(f"sha mismatch for {path}")
    return data


def secs_of(data):
    pe = pefile.PE(data=data, fast_load=True)
    return pe.OPTIONAL_HEADER.ImageBase, [
        (pe.OPTIONAL_HEADER.ImageBase + s.VirtualAddress, s.Misc_VirtualSize,
         s.PointerToRawData, s.SizeOfRawData,
         s.Name.rstrip(b"\0").decode(errors="replace")) for s in pe.sections]


def mk_dis(data):
    base, secs = secs_of(data)

    def va2off(va):
        for sva, vs, raw, sz, _n in secs:
            if sva <= va < sva + max(vs, sz):
                d = va - sva
                if d < sz:
                    return raw + d
        raise ValueError(hex(va))

    def dis(va, size):
        off = va2off(va)
        return [f"{i.address:08X}  {i.bytes.hex():<20} {i.mnemonic} {i.op_str}"
                for i in md.disasm(data[off:off + size], va)]

    def u32(va):
        off = va2off(va)
        return struct.unpack("<I", data[off:off + 4])[0]

    def u8n(va, n):
        off = va2off(va)
        return data[off:off + n]

    return dis, u32, u8n


