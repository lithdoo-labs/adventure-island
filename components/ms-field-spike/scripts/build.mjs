#!/usr/bin/env node
/**
 * Classic-script bundle for the isolated M1 spike.
 * Web Presentation Config v1 loads this as a classic script. It is not the
 * canonical cms-actor presentation entry.
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const componentRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sources = [
  path.join(componentRoot, "..", "..", "systems", "adventure-map", "content-database.mjs"),
  path.join(componentRoot, "src", "limits.mjs"),
  path.join(componentRoot, "src", "validate.mjs"),
  path.join(componentRoot, "src", "elements.mjs"),
];
const outputPath = path.join(componentRoot, "browser", "ms-field-spike.browser.js");
const HEADER = `/*! ms-field-spike browser entry (classic script; NOT an approved ABI).
 * Generated by components/ms-field-spike/scripts/build.mjs — edit src/ instead.
 * Isolated M1 fixture. The canonical PWA entry remains cms-actor. */`;

function stripModuleSyntax(source) {
  return source
    .replace(/\r\n/g, "\n")
    .replace(/^import\s*\{[\s\S]*?\}\s*from\s*["'][^"']+["'];\s*$/gm, "")
    .replace(/^export\s+(?=(const|function|class)\b)/gm, "");
}

function bundle() {
  const body = sources.map((file) => stripModuleSyntax(readFileSync(file, "utf8"))).join("\n\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  const script = `${HEADER}\n(function () {\n"use strict";\n${body}\n})();\n`;
  if (/(^|\n)\s*(import|export)\s/.test(script)) throw new Error("bundle still contains import/export syntax");
  return script;
}

const check = process.argv.includes("--check");
const generated = bundle();
if (check) {
  let current = null;
  try {
    current = readFileSync(outputPath, "utf8").replace(/\r\n/g, "\n");
  } catch {
    current = null;
  }
  if (current !== generated) {
    console.error("browser/ms-field-spike.browser.js is out of date; run: node components/ms-field-spike/scripts/build.mjs");
    process.exit(1);
  }
  console.log("browser/ms-field-spike.browser.js matches sources");
} else {
  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, generated);
  console.log(`wrote ${path.relative(componentRoot, outputPath)} (${Buffer.byteLength(generated)} bytes)`);
}

if (!check) {
  const syntax = spawnSync(process.execPath, ["--check", outputPath], { encoding: "utf8" });
  if (syntax.status !== 0) {
    console.error(syntax.stderr);
    process.exit(syntax.status ?? 1);
  }
}
