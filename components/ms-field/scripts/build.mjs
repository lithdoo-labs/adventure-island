#!/usr/bin/env node
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const componentRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sources = [
  path.join(componentRoot, "src", "limits.mjs"),
  path.join(componentRoot, "src", "resource-read-pool.mjs"),
  path.join(componentRoot, "..", "cms-actor", "src", "avatar-model.mjs"),
  path.join(componentRoot, "..", "ms-avatar", "src", "limits.mjs"),
  path.join(componentRoot, "..", "ms-avatar", "src", "action-clip.mjs"),
  path.join(componentRoot, "..", "ms-avatar", "src", "avatar-render-data.mjs"),
  path.join(componentRoot, "..", "ms-avatar", "src", "presentation-timing.mjs"),
  path.join(componentRoot, "..", "ms-avatar", "src", "presentation-attrs.mjs"),
  path.join(componentRoot, "..", "ms-avatar", "src", "compose-internal-plan.mjs"),
  path.join(componentRoot, "..", "ms-avatar", "src", "ms-action.mjs"),
  path.join(componentRoot, "..", "ms-avatar", "src", "ms-avatar.mjs"),
  path.join(componentRoot, "src", "validate.mjs"),
  path.join(componentRoot, "..", "ms-map-adapter", "src", "back-layout.mjs"),
  path.join(componentRoot, "src", "elements.mjs"),
];
const outputPath = path.join(componentRoot, "browser", "ms-field.browser.js");
const HEADER = `/*! ms-field browser entry (classic script; NOT an approved ABI).
 * Generated by components/ms-field/scripts/build.mjs — edit src/ instead.
 * M3 static Field scene for the canonical PWA entry. */`;

function stripModuleSyntax(source) {
  return source
    .replace(/\r\n/g, "\n")
    .replace(/^import\s*\{[\s\S]*?\}\s*from\s*["'][^"']+["'];\s*$/gm, "")
    .replace(/^import\s+[\s\S]*?\s+from\s*["'][^"']+["'];\s*$/gm, "")
    .replace(/^export\s+\{[\s\S]*?\};\s*$/gm, "")
    .replace(/^export\s+(?=(const|function|class)\b)/gm, "");
}

function bundle() {
  const body = sources.map((file) => stripModuleSyntax(readFileSync(file, "utf8"))).join("\n\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
  const script = `${HEADER}\n(function () {\n"use strict";\n${body}\n})();\n`;
  if (/(^|\n)\s*(import|export)\s/.test(script)) throw new Error("bundle still contains import/export syntax");
  return script;
}

const check = process.argv.includes("--check");
const generated = bundle();
if (check) {
  let current = null;
  try {
    current = readFileSync(outputPath, "utf8").replace(/\r\n/g, "\n");
  } catch {
    current = null;
  }
  if (current !== generated) {
    console.error("browser/ms-field.browser.js is out of date; run: node components/ms-field/scripts/build.mjs");
    process.exit(1);
  }
  console.log("browser/ms-field.browser.js matches sources");
} else {
  mkdirSync(path.dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, generated);
  console.log(`wrote ${path.relative(componentRoot, outputPath)} (${Buffer.byteLength(generated)} bytes)`);
}

if (!check) {
  const syntax = spawnSync(process.execPath, ["--check", outputPath], { encoding: "utf8" });
  if (syntax.status !== 0) {
    console.error(syntax.stderr);
    process.exit(syntax.status ?? 1);
  }
}