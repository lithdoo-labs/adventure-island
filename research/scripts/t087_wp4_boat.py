def window(va, size):
    lines = []
    for i in md.disasm(data[va - BASE:va - BASE + size], va):
        lines.append(f"{i.address:08X}  {i.bytes.hex():<22} {i.mnemonic} {i.op_str}")
    return '\n'.join(lines)


def u32(va):
    return struct.unpack('<I', data[va - BASE:va - BASE + 4])[0]


